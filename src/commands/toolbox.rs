use anyhow::{bail, Context, Result};
use clap::{Subcommand, ValueEnum};
use colored::Colorize;
use std::fs;
use std::path::PathBuf;

#[derive(Debug, Clone, Copy, ValueEnum)]
pub enum ToolboxTemplate {
    /// Ready-to-use DAS / Watershed delineation GUI tool for ArcGIS Pro & ModelBuilder
    Das,
    /// Ready-to-use Batch Reproject + Clip + Calculate Area (Ha) GUI tool
    BatchPrep,
    /// Clean starter Python Toolbox (.pyt) template for custom workflows
    Blank,
}

#[derive(Debug, Subcommand)]
pub enum ToolboxCommand {
    /// Generate a ModelBuilder-ready ArcGIS Python Toolbox (.pyt) with GUI parameters
    Create {
        /// Toolbox label/name (e.g. "GeoKit_DAS_Tools")
        name: String,
        /// Output .pyt file path
        #[arg(short, long)]
        out: PathBuf,
        /// Starter template: das, batch-prep, or blank
        #[arg(long, value_enum, default_value = "das")]
        template: ToolboxTemplate,
        /// Overwrite existing .pyt file
        #[arg(long)]
        force: bool,
    },
}

fn sanitize_alias(name: &str) -> String {
    let clean: String = name.chars().filter(|c| c.is_ascii_alphanumeric()).collect();
    if clean.is_empty() {
        "geokit".to_string()
    } else {
        clean.to_ascii_lowercase()
    }
}

fn render_pyt(name: &str, template: ToolboxTemplate) -> String {
    let alias = sanitize_alias(name);
    match template {
        ToolboxTemplate::Das => format!(
            r#"# -*- coding: utf-8 -*-
"""
{name} — ArcGIS Pro / ArcMap Python Toolbox (.pyt) generated by geokit.
Add this .pyt file in Catalog Pane or drag its tools directly into ModelBuilder!
"""

import os
import arcpy


class Toolbox(object):
    def __init__(self):
        self.label = "{name}"
        self.alias = "{alias}"
        self.tools = [DelineateWatershedTool]


class DelineateWatershedTool(object):
    def __init__(self):
        self.label = "DAS / Watershed Delineation (GeoKit)"
        self.description = (
            "Runs Fill -> Flow Direction -> Flow Accumulation -> Stream Network -> "
            "Watershed / Basins polygon extraction with automatic AREA_HA calculation."
        )
        self.canRunInBackground = False

    def getParameterInfo(self):
        dem = arcpy.Parameter(
            displayName="Input DEM Raster (Projected CRS recommended)",
            name="in_dem",
            datatype="GPRasterLayer",
            parameterType="Required",
            direction="Input",
        )
        threshold = arcpy.Parameter(
            displayName="Stream Accumulation Threshold (cells)",
            name="stream_threshold",
            datatype="GPLong",
            parameterType="Required",
            direction="Input",
        )
        threshold.value = 1000

        pour_point = arcpy.Parameter(
            displayName="Outlet / Pour Point (Optional — leave empty for all Basins)",
            name="pour_point",
            datatype="GPFeatureLayer",
            parameterType="Optional",
            direction="Input",
        )
        out_dir = arcpy.Parameter(
            displayName="Output Folder",
            name="out_folder",
            datatype="DEFolder",
            parameterType="Required",
            direction="Input",
        )
        out_poly = arcpy.Parameter(
            displayName="Output Watershed / Basins Polygon",
            name="out_watershed",
            datatype="DEFeatureClass",
            parameterType="Derived",
            direction="Output",
        )
        return [dem, threshold, pour_point, out_dir, out_poly]

    def isLicensed(self):
        return arcpy.CheckExtension("Spatial") == "Available"

    def execute(self, parameters, messages):
        arcpy.CheckOutExtension("Spatial")
        from arcpy import sa

        arcpy.env.overwriteOutput = True
        dem = parameters[0].valueAsText
        threshold = int(parameters[1].value)
        pour_point = parameters[2].valueAsText
        out_dir = parameters[3].valueAsText
        if not os.path.exists(out_dir):
            os.makedirs(out_dir)

        messages.addMessage("[1/4] Filling DEM sinks...")
        filled = sa.Fill(dem)
        filled.save(os.path.join(out_dir, "dem_filled.tif"))

        messages.addMessage("[2/4] Computing D8 Flow Direction & Accumulation...")
        fdir = sa.FlowDirection(filled, "NORMAL")
        fdir.save(os.path.join(out_dir, "flow_dir.tif"))
        facc = sa.FlowAccumulation(fdir)
        facc.save(os.path.join(out_dir, "flow_acc.tif"))

        messages.addMessage("[3/4] Extracting stream network...")
        streams_shp = os.path.join(out_dir, "streams.shp")
        sa.StreamToFeature(sa.Con(facc >= threshold, 1), fdir, streams_shp, "SIMPLIFY")

        messages.addMessage("[4/4] Delineating watershed / basins polygon...")
        if pour_point:
            snapped = sa.SnapPourPoint(pour_point, facc, 100)
            ws_ras = sa.Watershed(fdir, snapped)
            out_shp = os.path.join(out_dir, "watershed.shp")
        else:
            ws_ras = sa.Basin(fdir)
            out_shp = os.path.join(out_dir, "basins.shp")
        arcpy.conversion.RasterToPolygon(ws_ras, out_shp, "SIMPLIFY", "VALUE")
        arcpy.SetParameterAsText(4, out_shp)
        messages.addMessage("Done! Saved -> " + out_shp)
"#
        ),
        ToolboxTemplate::BatchPrep => format!(
            r#"# -*- coding: utf-8 -*-
"""
{name} — Batch Reproject, Clip & Area (Ha) Python Toolbox (.pyt) generated by geokit.
Ready to run in ArcGIS Pro Geoprocessing Pane or drag into ModelBuilder.
"""

import os
import arcpy


class Toolbox(object):
    def __init__(self):
        self.label = "{name}"
        self.alias = "{alias}"
        self.tools = [BatchClipProjectTool]


class BatchClipProjectTool(object):
    def __init__(self):
        self.label = "Batch Reproject & Clip Folder (GeoKit)"
        self.description = "Reprojects and clips all shapefiles in a folder against an AOI polygon."
        self.canRunInBackground = False

    def getParameterInfo(self):
        in_folder = arcpy.Parameter(
            displayName="Input Shapefile Folder",
            name="in_folder",
            datatype="DEFolder",
            parameterType="Required",
            direction="Input",
        )
        aoi = arcpy.Parameter(
            displayName="Clip AOI Polygon",
            name="aoi_poly",
            datatype="GPFeatureLayer",
            parameterType="Required",
            direction="Input",
        )
        sr = arcpy.Parameter(
            displayName="Target Coordinate System",
            name="target_sr",
            datatype="GPSpatialReference",
            parameterType="Required",
            direction="Input",
        )
        out_gdb = arcpy.Parameter(
            displayName="Output File Geodatabase (.gdb)",
            name="out_gdb",
            datatype="DEWorkspace",
            parameterType="Required",
            direction="Input",
        )
        return [in_folder, aoi, sr, out_gdb]

    def execute(self, parameters, messages):
        arcpy.env.overwriteOutput = True
        in_folder = parameters[0].valueAsText
        aoi = parameters[1].valueAsText
        sr = parameters[2].value
        out_gdb = parameters[3].valueAsText

        arcpy.env.workspace = in_folder
        shps = arcpy.ListFeatureClasses("*.shp") or []
        for idx, shp in enumerate(shps, 1):
            stem = os.path.splitext(shp)[0]
            tmp_proj = os.path.join("in_memory", stem + "_proj")
            out_fc = os.path.join(out_gdb, stem)
            arcpy.management.Project(shp, tmp_proj, sr)
            arcpy.analysis.Clip(tmp_proj, aoi, out_fc)
            messages.addMessage("[{{}}/{{}}] Processed {{}} -> {{}}".format(idx, len(shps), shp, out_fc))
"#
        ),
        ToolboxTemplate::Blank => format!(
            r#"# -*- coding: utf-8 -*-
"""
{name} — Starter Python Toolbox (.pyt) generated by geokit.
"""

import arcpy


class Toolbox(object):
    def __init__(self):
        self.label = "{name}"
        self.alias = "{alias}"
        self.tools = [CustomGeoKitTool]


class CustomGeoKitTool(object):
    def __init__(self):
        self.label = "Custom GeoKit Tool"
        self.description = "Custom tool ready for ArcGIS Pro and ModelBuilder."
        self.canRunInBackground = False

    def getParameterInfo(self):
        in_fc = arcpy.Parameter(
            displayName="Input Features",
            name="in_features",
            datatype="GPFeatureLayer",
            parameterType="Required",
            direction="Input",
        )
        out_fc = arcpy.Parameter(
            displayName="Output Features",
            name="out_features",
            datatype="DEFeatureClass",
            parameterType="Required",
            direction="Output",
        )
        return [in_fc, out_fc]

    def execute(self, parameters, messages):
        in_fc = parameters[0].valueAsText
        out_fc = parameters[1].valueAsText
        arcpy.management.CopyFeatures(in_fc, out_fc)
        messages.addMessage("Copied features -> " + out_fc)
"#
        ),
    }
}

pub fn run(cmd: ToolboxCommand) -> Result<()> {
    match cmd {
        ToolboxCommand::Create {
            name,
            out,
            template,
            force,
        } => {
            let dst = if out
                .extension()
                .and_then(|e| e.to_str())
                .map(|e| e.eq_ignore_ascii_case("pyt"))
                .unwrap_or(false)
            {
                out
            } else {
                out.with_extension("pyt")
            };

            if dst.exists() && !force {
                bail!(
                    "{} already exists. Use `--force` to overwrite.",
                    dst.display()
                );
            }
            if let Some(parent) = dst.parent() {
                if !parent.as_os_str().is_empty() {
                    fs::create_dir_all(parent)?;
                }
            }
            let content = render_pyt(&name, template);
            fs::write(&dst, content)
                .with_context(|| format!("Failed to write {}", dst.display()))?;
            println!(
                "{} Created ArcGIS Python Toolbox -> {}",
                "[OK]".green().bold(),
                dst.display()
            );
            println!("Open Catalog Pane in ArcGIS Pro/ArcMap, add this .pyt, or drag its tool straight into ModelBuilder!");
            Ok(())
        }
    }
}
