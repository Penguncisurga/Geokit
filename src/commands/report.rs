use anyhow::{bail, Context, Result};
use colored::Colorize;
use std::fs;
use std::path::Path;

use crate::gis::scanner::{format_bytes, scan_directory, ScanReport};
use crate::gis::GisCategory;

fn render_markdown(report: &ScanReport) -> String {
    let mut out = String::new();
    out.push_str("# GIS Workspace Inventory Report\n\n");
    out.push_str(&format!(
        "- **Root Directory**: `{}`\n",
        report.root.display()
    ));
    out.push_str(&format!(
        "- **Total Datasets**: {}\n",
        report.datasets.len()
    ));
    out.push_str(&format!(
        "- **Total Size**: {}\n",
        format_bytes(report.total_size_bytes)
    ));
    out.push_str(&format!(
        "- **Clutter Files**: {} `.lock`, {} temp\n\n",
        report.lock_files.len(),
        report.temp_files.len()
    ));

    let mut counts = [0usize; 5];
    for ds in &report.datasets {
        match ds.category {
            GisCategory::Vector => counts[0] += 1,
            GisCategory::Raster => counts[1] += 1,
            GisCategory::Geodatabase => counts[2] += 1,
            GisCategory::Project => counts[3] += 1,
            GisCategory::Tabular => counts[4] += 1,
        }
    }

    out.push_str("## Summary by Category\n\n");
    out.push_str("| Category | Count |\n| :--- | ---: |\n");
    out.push_str(&format!("| Vector | {} |\n", counts[0]));
    out.push_str(&format!("| Raster | {} |\n", counts[1]));
    out.push_str(&format!("| Geodatabase | {} |\n", counts[2]));
    out.push_str(&format!("| Project | {} |\n", counts[3]));
    out.push_str(&format!("| Tabular | {} |\n\n", counts[4]));

    out.push_str("## Datasets\n\n");
    out.push_str("| Category | Dataset | Files | Size | Status |\n");
    out.push_str("| :--- | :--- | ---: | ---: | :--- |\n");
    for ds in &report.datasets {
        let rel = ds
            .path
            .strip_prefix(&report.root)
            .unwrap_or(&ds.path)
            .display()
            .to_string();
        let status = if ds.issues.is_empty() {
            "OK".to_string()
        } else {
            ds.issues.join("; ")
        };
        out.push_str(&format!(
            "| {:?} | `{}` | {} | {} | {} |\n",
            ds.category,
            rel,
            ds.sidecar_count,
            format_bytes(ds.size_bytes),
            status
        ));
    }

    out.push_str("\n---\n*Generated by [geokit](https://github.com/Penguncisurga/Geokit)*\n");
    out
}

fn escape_html(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn render_html(report: &ScanReport) -> String {
    let mut rows = String::new();
    let mut issue_count = 0usize;
    for ds in &report.datasets {
        let rel = ds
            .path
            .strip_prefix(&report.root)
            .unwrap_or(&ds.path)
            .display()
            .to_string();
        let (badge_cls, status_text) = if ds.issues.is_empty() {
            ("ok", "OK".to_string())
        } else {
            issue_count += ds.issues.len();
            ("warn", ds.issues.join("; "))
        };
        rows.push_str(&format!(
            "<tr><td>{:?}</td><td><code>{}</code></td><td>{}</td><td>{}</td><td><span class=\"badge {}\">{}</span></td></tr>\n",
            ds.category,
            escape_html(&rel),
            ds.sidecar_count,
            format_bytes(ds.size_bytes),
            badge_cls,
            escape_html(&status_text)
        ));
    }

    format!(
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<title>GeoKit GIS Inventory Report</title>
<style>
  body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; margin: 2rem auto; max-width: 1100px; color: #1e293b; background: #f8fafc; }}
  h1 {{ color: #0f172a; margin-bottom: 0.25rem; }}
  .meta {{ color: #475569; margin-bottom: 1.5rem; font-size: 0.95rem; }}
  .cards {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(180px, 1fr)); gap: 1rem; margin-bottom: 1.5rem; }}
  .card {{ background: #fff; border: 1px solid #e2e8f0; border-radius: 10px; padding: 1rem 1.25rem; }}
  .card .label {{ font-size: 0.8rem; color: #64748b; text-transform: uppercase; letter-spacing: 0.04em; }}
  .card .val {{ font-size: 1.6rem; font-weight: 700; margin-top: 0.25rem; color: #0f172a; }}
  table {{ width: 100%; border-collapse: collapse; background: #fff; border-radius: 10px; overflow: hidden; border: 1px solid #e2e8f0; }}
  th, td {{ padding: 0.7rem 0.9rem; border-bottom: 1px solid #e2e8f0; text-align: left; font-size: 0.9rem; }}
  th {{ background: #f1f5f9; font-weight: 600; }}
  .badge {{ padding: 0.2rem 0.55rem; border-radius: 999px; font-size: 0.78rem; font-weight: 600; }}
  .badge.ok {{ background: #dcfce7; color: #166534; }}
  .badge.warn {{ background: #fef3c7; color: #92400e; }}
  footer {{ margin-top: 1.5rem; font-size: 0.8rem; color: #64748b; }}
</style>
</head>
<body>
  <h1>GIS Workspace Inventory Report</h1>
  <div class="meta">Root: <code>{}</code></div>
  <div class="cards">
    <div class="card"><div class="label">Datasets</div><div class="val">{}</div></div>
    <div class="card"><div class="label">Total Size</div><div class="val">{}</div></div>
    <div class="card"><div class="label">Warnings</div><div class="val">{}</div></div>
    <div class="card"><div class="label">Clutter (.lock/tmp)</div><div class="val">{}</div></div>
  </div>
  <table>
    <thead><tr><th>Category</th><th>Dataset</th><th>Files</th><th>Size</th><th>Status</th></tr></thead>
    <tbody>
      {}
    </tbody>
  </table>
  <footer>Generated by geokit v{}</footer>
</body>
</html>
"#,
        escape_html(&report.root.display().to_string()),
        report.datasets.len(),
        format_bytes(report.total_size_bytes),
        issue_count,
        report.lock_files.len() + report.temp_files.len(),
        rows,
        env!("CARGO_PKG_VERSION")
    )
}

pub fn run(path: &Path, out: &Path) -> Result<()> {
    if !path.is_dir() {
        bail!("Path must be an existing directory: {}", path.display());
    }
    let report = scan_directory(path);
    let ext = out
        .extension()
        .and_then(|e| e.to_str())
        .unwrap_or("md")
        .to_ascii_lowercase();

    let content = match ext.as_str() {
        "html" | "htm" => render_html(&report),
        "json" => serde_json::to_string_pretty(&report)?,
        _ => render_markdown(&report),
    };

    if let Some(parent) = out.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent)?;
        }
    }
    fs::write(out, content).with_context(|| format!("Failed to write {}", out.display()))?;
    println!(
        "{} Generated GIS inventory report -> {} ({} datasets)",
        "[OK]".green().bold(),
        out.display(),
        report.datasets.len()
    );
    Ok(())
}
